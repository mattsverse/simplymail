"""Regenerates crates/html/src/compat/data.rs from caniemail.com's data.

    python3 scripts/caniemail.py            # downloads https://www.caniemail.com/api/data.json
    python3 scripts/caniemail.py data.json  # or reads a copy already downloaded

Each feature keeps, for every client SimplyMail scores against, how the newest version caniemail
tested supports it: y (yes), a (partly), n (no) or u (untested).
"""

import json
import sys
import urllib.request
from pathlib import Path

URL = "https://www.caniemail.com/api/data.json"
OUT = Path(__file__).resolve().parent.parent / "crates/html/src/compat/data.rs"

# (caniemail family, Rust provider, [(caniemail platform, label)]), in the order shown.
