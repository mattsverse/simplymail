def latest(stats: dict, family: str, platform: str) -> str:
    """The support caniemail last recorded: versions are listed oldest first."""
    versions = stats.get(family, {}).get(platform, {})
    if not versions:
        return "u"
    value = list(versions.values())[-1].strip()
    return value[:1] if value[:1] in ("y", "a", "n") else "u"


def rust_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def main() -> None:
    if len(sys.argv) > 1:
        data = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    else:
        with urllib.request.urlopen(URL, timeout=60) as response:
            data = json.load(response)
    updated = data["last_update_date"][:10]
    lines = [
        f"// @generated by scripts/caniemail.py from caniemail.com's data of {updated}. Don't edit.",
        "//",
        LICENSE.rstrip("\n"),
        "",
        "use super::{Client, Feature, Provider};",
        "",
        "/// When caniemail last updated the data.",
        f"pub(super) const UPDATED: &str = {rust_str(updated)};",
        "",
        "/// Every client scored, in the order each [`Feature::support`] lists them.",
        "pub(super) static CLIENTS: &[Client] = &[",
    ]
    for _, provider, platforms in CLIENTS:
        for _, label in platforms:
            lines.append(f"    Client {{ provider: Provider::{provider}, platform: {rust_str(label)} }},")
    lines += ["];", "", "/// Sorted by slug.", "pub(super) static FEATURES: &[Feature] = &["]
    for feature in sorted(data["data"], key=lambda f: f["slug"]):
        support = "".join(
            latest(feature["stats"], family, platform)
            for family, _, platforms in CLIENTS
            for platform, _ in platforms
        )
        lines.append(
            f"    Feature {{ slug: {rust_str(feature['slug'])}, title: {rust_str(feature['title'])}, "
            f"support: {rust_str(support)} }},"
        )
    lines += ["];", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(data['data'])} features, updated {updated})")


if __name__ == "__main__":
    main()
