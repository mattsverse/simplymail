#!/usr/bin/env python3
"""Release metadata for SimplyMail (Python 3.11+)."""

import argparse
import json
import os
from pathlib import Path
import plistlib
import re
import subprocess
import sys
import tomllib

ROOT = Path(__file__).resolve().parent.parent
VERSION = re.compile(r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)")
# The workspace crate names release-please bumps in Cargo.lock.
LOCK_NAME = re.compile(r"@\.name\.value == '([^']+)'")
REPOSITORY = "mattsverse/simplymail"
FORMULA_VERSION = re.compile(r'^  version "([^"]+)"$', re.MULTILINE)


def version_parts(version):
    if not VERSION.fullmatch(version):
        raise ValueError(f"Expected a stable major.minor.patch version, got {version!r}")
    return tuple(map(int, version.split(".")))


def project_version():
    with (ROOT / "Cargo.toml").open("rb") as manifest:
        version = tomllib.load(manifest)["workspace"]["package"]["version"]
    version_parts(version)
    return version


def validate_tag(tag, version):
    if tag != f"v{version}":
        raise ValueError(f"Release tag {tag!r} must match Cargo.toml: v{version}")


def write_plist(output, version, build_number="1"):
    if not re.fullmatch(r"[1-9][0-9]{0,3}", build_number):
        raise ValueError("The bundle build number must be an integer from 1 to 9999")
    with (ROOT / "assets/macos/Info.plist").open("rb") as source:
        metadata = plistlib.load(source)
    metadata["CFBundleShortVersionString"] = version
    metadata["CFBundleVersion"] = build_number
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("wb") as target:
        plistlib.dump(metadata, target)


def formula_assets(version):
    """The release assets the Homebrew formula installs, by platform."""
    return {
        "macos": f"SimplyMail-{version}-universal.zip",
        "linux_arm": f"simplymail-{version}-aarch64-unknown-linux-gnu.tar.gz",
        "linux_intel": f"simplymail-{version}-x86_64-unknown-linux-gnu.tar.gz",
    }


def parse_sums(text):
    """Reads `sha256sum` output into {file name: digest}."""
    sums = {}
    for line in text.splitlines():
        if not line.strip():
            continue
        match = re.fullmatch(r"([0-9a-f]{64}) [ *]?(\S+)", line.strip())
        if not match:
            raise ValueError(f"Malformed SHA256SUMS line: {line!r}")
        sums[match.group(2)] = match.group(1)
    return sums


def render_formula(version, sums):
    version_parts(version)
    base = f"https://github.com/{REPOSITORY}/releases/download/v{version}"
    assets = formula_assets(version)
    missing = sorted(name for name in assets.values() if name not in sums)
    if missing:
        raise ValueError(f"SHA256SUMS lacks the formula's assets: {missing}")
    url = {key: f"{base}/{name}" for key, name in assets.items()}
    sha = {key: sums[name] for key, name in assets.items()}
    return f'''# Generated by scripts/release.py in {REPOSITORY}; edits are overwritten on release.
class Simplymail < Formula
  desc "Local, privacy-focused, no-frills email"
  homepage "https://github.com/{REPOSITORY}"
  version "{version}"
  license "MIT"

  # One universal app, signed and notarized, for Apple silicon and Intel Macs.
  if OS.mac?
    url "{url["macos"]}"
    sha256 "{sha["macos"]}"
  elsif Hardware::CPU.arm?
    url "{url["linux_arm"]}"
    sha256 "{sha["linux_arm"]}"
  else
    url "{url["linux_intel"]}"
    sha256 "{sha["linux_intel"]}"
  end

  on_macos do
    depends_on macos: :ventura
  end

  def install
    if OS.mac?
      # Homebrew steps into an archive's only directory, which here is the app itself.
      if File.directory?("Contents")
        (prefix/"SimplyMail.app").install "Contents"
      else
        prefix.install "SimplyMail.app"
      end
      # A script, not a symlink, so the app runs from its bundle and keeps its identity.
      bin.write_exec_script prefix/"SimplyMail.app/Contents/MacOS/simplymail"
    else
      bin.install "simplymail"
    end
  end

  def caveats
    return unless OS.mac?

    <<~EOS
      Run `simplymail`, or put SimplyMail in your Applications folder with:
        ln -sf "#{{opt_prefix}}/SimplyMail.app" ~/Applications/SimplyMail.app
    EOS
  end

  test do
    assert_predicate bin/"simplymail", :executable?
  end
end
'''


def write_formula(output, version, sums_text):
    """Writes the formula, refusing to replace a newer version already in the tap."""
    if output.exists():
        current = FORMULA_VERSION.search(output.read_text())
        if current and version_parts(current.group(1)) > version_parts(version):
            raise ValueError(f"The tap already has {current.group(1)}; refusing to downgrade to {version}")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render_formula(version, parse_sums(sums_text)))


def release_please_lock_names(config):
    for extra in config["packages"]["."]["extra-files"]:
        if extra["path"] == "Cargo.lock":
            return set(LOCK_NAME.findall(extra["jsonpath"]))
    raise ValueError("release-please-config.json does not bump Cargo.lock")


def workspace_names():
    metadata = subprocess.run(
        ["cargo", "metadata", "--no-deps", "--format-version", "1", "--locked"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    )
    return {package["name"] for package in json.loads(metadata.stdout)["packages"]}


def check_config():
    """Fail when a workspace crate is added or renamed without updating release-please."""
    config = json.loads((ROOT / "release-please-config.json").read_text())
    configured, actual = release_please_lock_names(config), workspace_names()
    if configured != actual:
        missing, extra = sorted(actual - configured), sorted(configured - actual)
        raise ValueError(
            "release-please-config.json must bump every workspace crate in Cargo.lock "
            f"(missing: {missing}, unknown: {extra})"
        )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    metadata = commands.add_parser("version")
    metadata.add_argument("--tag")
    plist = commands.add_parser("plist")
    plist.add_argument("--output", type=Path, required=True)
    plist.add_argument("--build-number", default=os.environ.get("GITHUB_RUN_NUMBER", "1"))
    commands.add_parser("check-config")
    formula = commands.add_parser("formula", help="Write the Homebrew formula for a release")
    formula.add_argument("--tag", required=True)
    formula.add_argument("--sums", type=Path, required=True, help="The release's SHA256SUMS")
    formula.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.command == "check-config":
        check_config()
        return
    if args.command == "formula":
        # The tap job runs on the tag, so the tag and Cargo.toml agree; take the version from the tag.
        version = args.tag.removeprefix("v")
        validate_tag(args.tag, version)
        write_formula(args.output, version, args.sums.read_text())
        return
    version = project_version()
    if args.command == "version":
        if args.tag:
            validate_tag(args.tag, version)
        print(version)
    elif args.command == "plist":
        write_plist(args.output, version, args.build_number)


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        sys.exit(str(error))
